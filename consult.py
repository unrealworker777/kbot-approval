_HISTORY = {}
_LEAD_SENT = set()
MAX_TURNS = 12


def _load_kb():
    path = Path(config.KNOWLEDGE_BASE_PATH)
    if path.exists():
        return path.read_text(encoding="utf-8")
    return "(база знаний не задана)"


def history(user_id):
    return _HISTORY.get(user_id, [])


def reply(user_id, text, user_name=""):
    """Генерирует ответ ассистента с учётом истории диалога."""
    msgs = list(_HISTORY.get(user_id, []))
    msgs.append({"role": "user", "content": text})

    system = SYSTEM_PROMPT.format(knowledge_base=_load_kb())
    if user_name:
        system += f"\n\nИмя собеседника: {user_name}"

    try:
        r = _client.messages.create(
            model=config.CONSULT_MODEL,
            max_tokens=600,
            system=system,
            messages=msgs[-MAX_TURNS:],
        )
        answer = "".join(b.text for b in r.content if b.type == "text").strip()
    except Exception as e:
        print(f"[consult] ошибка генерации: {e}")
        return None

    msgs.append({"role": "assistant", "content": answer})
    _HISTORY[user_id] = msgs[-MAX_TURNS:]
    return answer


LEAD_PROMPT = """Проанализируй диалог ассистента ИПМ с человеком.
Определи, пора ли заводить лид в CRM: человек ЯВНО согласился на консультацию,
оставил телефон/почту, или дал кадастровый номер и просит разбор.

Верни ТОЛЬКО JSON, без пояснений:
{"lead": true/false, "phone": "", "email": "", "cadastre": "", "area": "", "region": "", "status": "", "summary": ""}

lead=true только при явном интересе или переданном контакте. Пустые поля — "".
summary — одна строка: что человек хочет."""


def detect_lead(user_id):
    """Смотрит историю: пора ли создавать лид. Возвращает dict или None."""
    if user_id in _LEAD_SENT:
        return None
    msgs = _HISTORY.get(user_id, [])
    if len(msgs) < 2:
        return None

    dialog = "\n".join(
        f"{'ЧЕЛОВЕК' if m['role'] == 'user' else 'АССИСТЕНТ'}: {m['content']}"
        for m in msgs[-MAX_TURNS:]
    )
    try:
        r = _client.messages.create(
            model=config.FILTER_MODEL,
            max_tokens=300,
            system=LEAD_PROMPT,
            messages=[{"role": "user", "content": dialog[:6000]}],
        )
        raw = "".join(b.text for b in r.content if b.type == "text").strip()
        raw = raw.replace("```json", "").replace("```", "").strip()
        data = json.loads(raw)
    except Exception as e:
        print(f"[consult] детект лида не сработал: {e}")
        return None

    if not data.get("lead"):
        return None
    _LEAD_SENT.add(user_id)
    data["summary"] = data.get("summary") or "Обращение из Telegram"
    return data
